/* Card Component */
/* ========================================================================== */

import { HTMLAttributes, forwardRef } from 'react';

export interface CardProps extends HTMLAttributes<HTMLDivElement> {
  variant?: 'default' | 'elevated' | 'outlined';
  padding?: 'none' | 'sm' | 'md' | 'lg';
  hoverable?: boolean;
}

export const Card = forwardRef<HTMLDivElement, CardProps>(
  ({ variant = 'default', padding = 'md', hoverable = false, className = '', children, ...props }, ref) => {
    const variantClasses = {
      default: 'bg-surface border border-border rounded-xl',
      elevated: 'bg-surface-elevated shadow-lg rounded-xl border-none',
      outlined: 'bg-surface border-2 border-border-strong rounded-xl',
    };
    
    const paddingClasses = {
      none: '',
      sm: 'p-4',
      md: 'p-6',
      lg: 'p-8',
    };
    
    const hoverClass = hoverable ? 'transition-all hover:shadow-lg hover:border-border-strong' : '';
    
    const combinedClass = `${variantClasses[variant]} ${paddingClasses[padding]} ${hoverClass} ${className}`.trim();
    
    return (
      <div ref={ref} className={combinedClass} {...props}>
        {children}
      </div>
    );
  }
);

Card.displayName = 'Card';

